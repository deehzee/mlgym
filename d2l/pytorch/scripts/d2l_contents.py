"""Print the book's chapter/section structure with the matching bundle notebook.

usage, from the repo root (stdlib only):
    python3 d2l/pytorch/scripts/d2l_contents.py d2l/d2l-neu d2l/pytorch/bundle \
        > d2l/pytorch/CONTENTS.md

Order comes from _quarto.yml (parts -> chapters -> sections). Titles are the first
`# heading` of each source .md (outside code fences). Chapters are numbered in order,
skipping the preface part and the attic; sections are numbered n.m by their order.
"""
import os
import re
import subprocess
import sys

src, bundle = sys.argv[1], sys.argv[2]
sha = subprocess.run(["git", "-C", src, "rev-parse", "--short", "HEAD"],
                     capture_output=True, text=True).stdout.strip() or "unknown"


def title(path):
    if not os.path.exists(path):
        return "(no source)"
    fence = False
    for line in open(path, encoding="utf-8"):
        if line.lstrip().startswith("```"):
            fence = not fence
        elif not fence and line.startswith("# "):
            return line[2:].strip()
    return "(untitled)"


# _quarto.yml -> [(part_dir, [(chapter_dir, [section, ...]), ...]), ...]
parts, part, chap = [], None, None
for line in open(f"{src}/_quarto.yml", encoding="utf-8"):
    m = re.match(r"\s*- part: (chapter_[\w\-]+)/index\.qmd", line)
    if m:
        part = (m.group(1), [])
        parts.append(part)
        continue
    m = re.match(r"\s*- (chapter_[\w\-]+)/([\w\-]+)\.qmd", line)
    if m and part:
        c, f = m.groups()
        if f == "index":
            chap = (c, [])
            part[1].append(chap)
        elif chap:
            chap[1].append(f)

have = {
    (c, f[:-6])
    for c in os.listdir(bundle) if c.startswith("chapter_")
    for f in os.listdir(f"{bundle}/{c}") if f.endswith(".ipynb")
}

n = 0
total = missing = 0
out = []
for pdir, chapters in parts:
    unnumbered = pdir in ("chapter_preface", "chapter_attic")
    out.append(f"\n## {title(f'{src}/{pdir}/index.md')}\n")
    for cdir, sections in chapters:
        if not unnumbered:
            n += 1
        label = "" if unnumbered else f"{n} "
        out.append(f"### {label}{title(f'{src}/{cdir}/index.md')}  (`{cdir}`)\n")
        if not sections:
            out.append("(prose only, no section files)\n")
            continue
        out.append("| Section | Title | Notebook |\n|---|---|---|")
        for i, s in enumerate(sections, 1):
            num = f"{n}.{i}" if not unnumbered else f"{i}"
            total += 1
            if (cdir, s) in have:
                # link relative to CONTENTS.md, which sits next to the bundle dir
                nb = f"[{cdir}/{s}.ipynb]({os.path.basename(bundle.rstrip('/'))}/{cdir}/{s}.ipynb)"
            else:
                # Why there is no notebook: no source file, a source with no Python
                # code (text only), or a source with code that the bundle lacks.
                md = f"{src}/{cdir}/{s}.md"
                text = open(md, encoding="utf-8").read() if os.path.exists(md) else None
                if text is None:
                    nb = "no source file"
                elif "<!-- Author brief" in text:
                    nb = "not yet written (author brief only)"
                elif not re.search(r"^```\{?\.?python", text, re.M):
                    nb = "text only, no code"
                else:
                    nb = "has code, not in bundle"
                missing += 1
            out.append(f"| {num} | {title(f'{src}/{cdir}/{s}.md')} | {nb} |")
        out.append("")

print("# Contents: sections and notebooks\n")
print(f"Generated by `scripts/d2l_contents.py` from d2l-neu `{sha}` and `bundle/`. "
      "Regenerate after updating either.\n")
print(f"{total} sections listed in `_quarto.yml`; {total - missing} have a notebook in the bundle, "
      f"{missing} do not. A section without a notebook is one of: "
      "`not yet written (author brief only)` (the source `.md` is a skeleton holding "
      "only the author's planning brief), `text only, no code` (written prose with no "
      "Python code block), `has code, not in bundle` (source has code but the bundle "
      "lacks the notebook) or `no source file` (listed in `_quarto.yml` but the `.md` "
      "is missing). `_quarto.yml` names `.qmd` files, but those are generated from the "
      "`.md` sources at build time.")
print("\n".join(out))
